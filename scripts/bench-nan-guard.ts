// ═══════════════════════════════════════════════════════════════════
// Angusht v2.4.4 — регрессионная проверка: "теневые" отрицательные индексы
// ═══════════════════════════════════════════════════════════════════
// Найденный баг: (h >> 6)/(h >> 12) — знаковый сдвиг 32-битного числа в
// JS. При установленном старшем бите хеша результат отрицателен;
// idx(l,r,c) = (l*GRID+r)*GRID+c без нормализации мог уйти в
// отрицательный индекс. Float32Array молча трактует его как обычное
// свойство объекта (не элемент буфера) — чтение назад даёт undefined,
// первая же арифметика (undefined + x) даёт NaN, а из-за инварианта
// "потенциал/адаптация ненулевые → нейрон в liveSet" (см. neural-core.ts)
// заражённый индекс НИКОГДА не покидает liveSet — NaN в avgPotential
// становится ПОСТОЯННЫМ до перезапуска процесса (JSON.stringify(NaN)
// === "null" → падение UI на .toFixed()).
//
// Этот скрипт не сравнивает с baseline — он проганяет кластер через
// реалистичную нагрузку (много разных текстов, много раундов) и
// проверяет, что avgPotential/avgWeight КАЖДОГО ядра остаются конечными
// числами на каждом шаге. Раньше это ловилось только руками в браузере.
//
// Запуск: npx tsx scripts/bench-nan-guard.ts
// ═══════════════════════════════════════════════════════════════════

import { CoreCluster } from '../src/lib/neuromorphic/core-cluster';

const TEXTS = [
  'кошка спит на диване', 'собака гуляет в парке', 'нейрон передаёт сигнал',
  'python используется для обучения', 'гравитация притягивает тела',
  '2+2', '15*3', 'что такое чёрная дыра', 'кто ты', 'расскажи о фотосинтезе',
  'блокчейн это распределённый реестр', 'квантовая механика',
  'привет, как дела', 'сколько будет 100 разделить на 4',
  'объясни теорию относительности', 'кошка снова на диване спит',
  'что такое искусственный интеллект', 'память и обучение',
  'нейросети и глубокое обучение', 'вселенная и звёзды',
];

let failures = 0;
const cluster = new CoreCluster();

for (let round = 0; round < 60; round++) {
  const text = TEXTS[round % TEXTS.length];
  cluster.processInput(text);

  for (const core of cluster.cores.values()) {
    const snap = core.snapshot();
    if (!Number.isFinite(snap.avgPotential) || !Number.isFinite(snap.avgWeight)) {
      failures++;
      console.log(`[FAIL] раунд ${round}, текст="${text}", ядро=${core.id}: avgPotential=${snap.avgPotential}, avgWeight=${snap.avgWeight}`);
      if (failures > 5) {
        console.log('...остановлено после 5 находок');
        process.exit(1);
      }
    }
  }

  // Дополнительно: фоновая спонтанная стимуляция (тоже маршрутизирует
  // сигналы через те же обучаемые проекции) — отдельный путь появления
  // тех же "теневых" индексов, если бы фикс был неполным.
  if (round % 10 === 0) {
    cluster.spontaneousStimulation(200);
  }
}

if (failures === 0) {
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ ✓ (${TEXTS.length} текстов × 60 раундов, avgPotential/avgWeight всегда конечны)`);
} else {
  console.log(`\n${failures} НАХОДОК ✗`);
}
process.exitCode = failures === 0 ? 0 : 1;
