// ═══════════════════════════════════════════════════════════════════
// Цель: превратить "интернет" и "интернета", "кошка" и "кошки",
// "программирование" и "программист" в один и тот же токен для
// сопоставления, плюс расширить запрос смысловыми синонимами.
// Это НЕ полноценная NLP-модель — это лёгкий детерминированный слой,
// который убирает главный источник "несуразицы": сравнение текстов
// по сырым подстрокам без учёта словоформ и смысловой близости.
// ═══════════════════════════════════════════════════════════════════

export const STOP_WORDS = new Set([
  'в', 'на', 'и', 'с', 'о', 'по', 'к', 'из', 'за', 'от', 'для',
  'что', 'это', 'как', 'не', 'а', 'но', 'да', 'или', 'если', 'же',
  'the', 'a', 'an', 'is', 'are', 'was', 'were', 'be', 'been',
  'do', 'does', 'did', 'will', 'would', 'could', 'should', 'can',
  'of', 'in', 'to', 'for', 'with', 'on', 'at', 'by', 'from', 'it',
  'какой', 'какая', 'какие', 'где', 'когда', 'почему', 'зачем',
  'кто', 'чем', 'мне', 'ты', 'вы', 'он', 'она', 'они', 'мы',
  'все', 'этот', 'тот', 'свой', 'мой', 'ваш', 'наш', 'их', 'есть',
  'может', 'был', 'была', 'были', 'будет', 'могут', 'так', 'еще',
]);

// ── Лёгкий стеммер для русского: последовательно отрезает самую
// длинную подходящую словоформенную концовку, если остаток >= 3 букв.
// Не претендует на лингвистическую точность (в отличие от полного
// алгоритма Портера для русского) — но покрывает основные падежные,
// числовые и глагольные окончания, чего достаточно для сопоставления
// однокоренных слов в чате.
const RU_SUFFIXES = [
  'иями', 'ями', 'ами', 'его', 'ому', 'ему', 'ыми', 'ими', 'ого', 'ием',
  'ая', 'яя', 'ое', 'ее', 'ий', 'ый', 'ой', 'ей', 'ые', 'ие', 'ия', 'ию', 'ии',
  'ов', 'ев', 'ах', 'ях', 'ам', 'ям', 'ом', 'ем', 'ую', 'юю',
  'ешь', 'ишь', 'ете', 'ите', 'ют', 'ут', 'ат', 'ят',
  'ла', 'ло', 'ли', 'ть', 'шь',
  'а', 'я', 'ы', 'и', 'у', 'ю', 'о', 'е', 'й', 'ь',
].sort((a, b) => b.length - a.length);

function stemRu(word: string): string {
  if (word.length <= 3) return word;
  for (const suf of RU_SUFFIXES) {
    if (word.endsWith(suf) && word.length - suf.length >= 3) {
      return word.slice(0, word.length - suf.length);
    }
  }
  return word;
}

const EN_SUFFIXES = ['ing', 'ies', 'ied', 'edly', 'ed', 'es', 'ly', 's'].sort(
  (a, b) => b.length - a.length
);

function stemEn(word: string): string {
  for (const suf of EN_SUFFIXES) {
    if (word.endsWith(suf) && word.length - suf.length >= 3) {
      if (suf === 'ies') return word.slice(0, -3) + 'y';
      return word.slice(0, word.length - suf.length);
    }
  }
  return word;
}

export function stemWord(word: string): string {
  if (/^[a-z0-9]+$/.test(word)) return stemEn(word);
  if (/^[а-яё0-9]+$/.test(word)) return stemRu(word);
  return word;
}

// Токенизация с нормализацией: разбивает текст на слова, убирает
// стоп-слова, приводит каждое слово к основе (стему).
// ё→е приводится до разбиения на слова: в обычном письме "ё" почти
// всегда заменяют на "е" ("черная дыра" вместо "чёрная дыра"), и без
// этой нормализации такие запросы не находили тему в базе знаний.
export function tokenizeNormalized(text: string): string[] {
  const normalized = text.toLowerCase().replace(/ё/g, 'е');
  const words = normalized.match(/[a-zA-Zа-яА-Я0-9]{2,}/g) || [];
  const out: string[] = [];
  for (const w of words) {
    if (STOP_WORDS.has(w)) continue;
    out.push(stemWord(w));
  }
  return out;
}

// ── Синонимические группы ──
// Небольшой, кураторский набор смысловых кластеров вокруг тем,
// присутствующих в базе знаний и типичных бытовых запросах. Это не
// исчерпывающий тезаурус — он расширяем добавлением новых массивов.
const RAW_SYNONYM_GROUPS: string[][] = [
  ['огонь', 'пламя', 'пожар', 'костёр', 'костер'],
  ['вода', 'жидкость', 'влага'],
  ['земля', 'планета'],
  ['солнце', 'звезда', 'светило'],
  ['луна', 'месяц'],
  ['гравитация', 'тяготение', 'притяжение'],
  ['квант', 'квантовый', 'кванты'],
  ['свет', 'освещение', 'сияние'],
  ['атом', 'атомный', 'атомы'],
  ['электрон', 'электроны'],
  ['мозг', 'головной', 'разум'],
  ['нейрон', 'нейроны'],
  ['клетка', 'клеточный'],
  ['эволюция', 'эволюционный', 'дарвин'],
  ['фотосинтез'],
  ['кошка', 'кот', 'котёнок', 'котенок'],
  ['собака', 'пёс', 'пес', 'щенок'],
  ['дельфин', 'дельфины'],
  ['питон', 'python'],
  ['типескрипт', 'typescript'],
  ['javascript', 'джаваскрипт'],
  ['реакт', 'react'],
  ['нейросеть', 'нейросети'],
  ['интеллект', 'ии', 'ai'],
  ['блокчейн', 'крипта', 'криптовалюта', 'биткоин'],
  ['время', 'времени'],
  ['энергия', 'энергетика'],
  ['электричество', 'ток', 'электрический'],
  ['интернет', 'сеть', 'wifi', 'вайфай'],
  ['программирование', 'код', 'кодинг', 'программист'],
];

export const SYNONYM_GROUPS: string[][] = RAW_SYNONYM_GROUPS.map((g) => [
  ...new Set(g.map(stemWord)),
]);

const STEM_TO_GROUP = new Map<string, number>();
SYNONYM_GROUPS.forEach((g, i) => g.forEach((s) => STEM_TO_GROUP.set(s, i)));

// Расширяет уже нормализованный (стеммированный) список токенов
// синонимами из тех же смысловых групп. Используется и для запроса
// (чтобы "тяготение" находило статью про "гравитацию"), и, при
// желании, для индексации, чтобы синонимы попадали в один "куст".
export function expandWithSynonyms(tokens: string[]): string[] {
  const out = new Set(tokens);
  for (const t of tokens) {
    const gi = STEM_TO_GROUP.get(t);
    if (gi !== undefined) {
      for (const s of SYNONYM_GROUPS[gi]) out.add(s);
    }
  }
  return [...out];
}
